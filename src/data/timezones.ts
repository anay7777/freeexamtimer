export function findCountryTimeZone(id: string | null | undefined): CountryTimeZone {
  if (!id || id === 'local') return MAJOR_COUNTRY_TIMEZONES[0];
  const found = MAJOR_COUNTRY_TIMEZONES.find((tz) => tz.id === id);
  return found || MAJOR_COUNTRY_TIMEZONES[0];
}

export function formatClockWithZone(
  date: Date,
  hour12: boolean,
  withSeconds = true,
  timeZoneId = 'local'
): string {
  const opts: Intl.DateTimeFormatOptions = {
    hour: 'numeric',
    minute: '2-digit',
    hour12,
  };
  if (withSeconds) opts.second = '2-digit';
  if (timeZoneId && timeZoneId !== 'local') {
    opts.timeZone = timeZoneId;
  }
  try {
    return date.toLocaleTimeString(undefined, opts);
  } catch {
    delete opts.timeZone;
    return date.toLocaleTimeString(undefined, opts);
  }
}
